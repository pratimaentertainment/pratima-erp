import crypto from 'crypto';

const ALGORITHM = 'aes-256-gcm';
const IV_LENGTH = 12; // 96-bit IV recommended by NIST for AES-GCM
const AUTH_TAG_LENGTH = 16; // 128-bit authentication tag

/**
 * Retrieves and validates the 32-byte master encryption key from environment.
 * Accepts:
 * - 64-character hex string (32 bytes)
 * - 32-character utf-8 string
 * - 44-character base64 string
 */
function getEncryptionKey(): Buffer {
  const rawKey = process.env.ENCRYPTION_KEY;
  if (!rawKey) {
    throw new Error('FATAL SECURITY ERROR: ENCRYPTION_KEY environment variable is not set.');
  }

  let keyBuffer: Buffer;

  // Check 64-char hex string
  if (rawKey.length === 64 && /^[0-9a-fA-F]+$/.test(rawKey)) {
    keyBuffer = Buffer.from(rawKey, 'hex');
  } else if (Buffer.byteLength(rawKey, 'utf8') === 32) {
    keyBuffer = Buffer.from(rawKey, 'utf8');
  } else {
    // Attempt base64 decode
    const b64 = Buffer.from(rawKey, 'base64');
    if (b64.length === 32) {
      keyBuffer = b64;
    } else {
      throw new Error(
        `FATAL SECURITY ERROR: ENCRYPTION_KEY must be exactly 32 bytes (256 bits). Current length: ${Buffer.byteLength(
          rawKey,
          'utf8'
        )} bytes.`
      );
    }
  }

  if (keyBuffer.length !== 32) {
    throw new Error(
      `FATAL SECURITY ERROR: Parsed ENCRYPTION_KEY buffer is ${keyBuffer.length} bytes, expected 32 bytes.`
    );
  }

  return keyBuffer;
}

/**
 * Encrypts arbitrary text using AES-256-GCM.
 * Output format: `<iv_hex>:<auth_tag_hex>:<ciphertext_hex>`
 * 
 * @param text Plaintext to encrypt
 * @returns Serialized encrypted string containing IV, Auth Tag, and Ciphertext
 */
export function encryptData(text: string): string {
  if (typeof text !== 'string') {
    throw new TypeError('Plaintext data must be a string');
  }

  const key = getEncryptionKey();
  const iv = crypto.randomBytes(IV_LENGTH);

  const cipher = crypto.createCipheriv(ALGORITHM, key, iv, {
    authTagLength: AUTH_TAG_LENGTH,
  });

  let encrypted = cipher.update(text, 'utf8', 'hex');
  encrypted += cipher.final('hex');

  const authTag = cipher.getAuthTag();

  return `${iv.toString('hex')}:${authTag.toString('hex')}:${encrypted}`;
}

/**
 * Decrypts an AES-256-GCM encrypted string.
 * Expects format: `<iv_hex>:<auth_tag_hex>:<ciphertext_hex>`
 * 
 * @param encryptedText Serialized string generated by encryptData
 * @returns Original plaintext
 */
export function decryptData(encryptedText: string): string {
  if (typeof encryptedText !== 'string' || !encryptedText) {
    throw new TypeError('Encrypted text must be a non-empty string');
  }

  const parts = encryptedText.split(':');
  if (parts.length !== 3) {
    throw new Error('Invalid encrypted data format. Expected iv:authTag:ciphertext');
  }

  const [ivHex, authTagHex, ciphertextHex] = parts;
  const key = getEncryptionKey();

  const iv = Buffer.from(ivHex, 'hex');
  const authTag = Buffer.from(authTagHex, 'hex');

  if (iv.length !== IV_LENGTH) {
    throw new Error(`Corrupted ciphertext: invalid IV length (${iv.length} bytes)`);
  }

  if (authTag.length !== AUTH_TAG_LENGTH) {
    throw new Error(`Corrupted ciphertext: invalid Auth Tag length (${authTag.length} bytes)`);
  }

  const decipher = crypto.createDecipheriv(ALGORITHM, key, iv, {
    authTagLength: AUTH_TAG_LENGTH,
  });

  decipher.setAuthTag(authTag);

  try {
    let decrypted = decipher.update(ciphertextHex, 'hex', 'utf8');
    decrypted += decipher.final('utf8');
    return decrypted;
  } catch (error: any) {
    throw new Error(`Decryption failed: Message authentication tag mismatch or corrupted data. ${error.message}`);
  }
}

/**
 * Helper to encrypt any JSON-serializable object.
 */
export function encryptJSON<T = unknown>(obj: T): string {
  return encryptData(JSON.stringify(obj));
}

/**
 * Helper to decrypt and parse a JSON-serialized object.
 */
export function decryptJSON<T = unknown>(encryptedText: string): T {
  const decrypted = decryptData(encryptedText);
  return JSON.parse(decrypted) as T;
}
